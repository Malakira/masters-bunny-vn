// =====================================================
// AUDIO HELPERS
// =====================================================

function stopAudio(audio) {
    audio.pause();
    audio.currentTime = 0;
}


function stopAmbientAudio() {

    stopAudio(forestscary);
    stopAudio(cemetery);
    stopAudio(creepsi);
}


function stopAllAudio() {

    stopAudio(mainTheme);
    stopAudio(memeAudio);
    stopAudio(goodEndingAudio);
    stopAudio(badEndingAudio);

    stopAmbientAudio();
}


function playMainTheme() {

    stopAudio(goodEndingAudio);
    stopAudio(badEndingAudio);

    mainTheme.play().catch(() => {
        console.log("Main theme waiting for player interaction.");
    });
}


function playMemeAudio() {

    mainTheme.pause();

    memeAudio.currentTime = 0;

    memeAudio.play().catch(() => {
        console.log("Meme audio waiting for player interaction.");
    });
}


function resumeMainTheme() {

    memeAudio.pause();
    memeAudio.currentTime = 0;

    mainTheme.play().catch(() => {});
}


// =====================================================
// SCENE TRANSITION
// =====================================================

function changeScene(image) {

    scene.classList.add("fade-out");

    setTimeout(() => {

        scene.style.backgroundImage = `url("${image}")`;

        scene.classList.remove("fade-out");

    }, 800);
}


// =====================================================
// TYPEWRITER
// =====================================================

function typeText(message) {

    clearInterval(typingTimer);

    typing = true;

    text.textContent = "";

    let index = 0;

    typingTimer = setInterval(() => {

        text.textContent += message[index];

        index++;

        if (index >= message.length) {

            clearInterval(typingTimer);

            typing = false;
        }

    }, 25);
}


