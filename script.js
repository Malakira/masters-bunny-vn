// =====================================================
// CONTINUE BUTTON
// =====================================================

button.addEventListener("click", () => {


    // -----------------------------------------
    // FINAL SCREEN
    // -----------------------------------------

    if (gameState === "final") {

        returnToChoice();

        return;
    }


    // -----------------------------------------
    // FINISH CURRENT TYPING
    // -----------------------------------------

    if (typing) {

        clearInterval(typingTimer);

        text.textContent =
            gameState === "ending"
                ? endingLines[endingIndex].text
                : dialogue[currentLine].text;

        typing = false;

        return;
    }


    // -----------------------------------------
    // ENDING DIALOGUE
    // -----------------------------------------

if (gameState === "ending") {

        endingIndex++;

        if (endingIndex < endingLines.length) {

            const line = endingLines[endingIndex];

            speaker.textContent = line.speaker;
            typeText(line.text);

            // Ending scene triggers go here
            if (line.text === "She was standing outside the academy.") {
                changeScene("assets/collage.jpg");
                bunny.style.display = "none";
            }

        } else {

            showFinalMessage();

        }

        return;
    }
    // -----------------------------------------
    // NORMAL DIALOGUE
    // -----------------------------------------

    if (gameState !== "dialogue") {

        return;
    }


    currentLine++;


    if (currentLine < dialogue.length) {

        showDialogue();

    } else {

        startChoice();
    }
});


